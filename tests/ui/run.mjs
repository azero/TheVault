async function step(name, fn) {
  if (only && !name.includes(only)) return
  const t = Date.now()
  try { await fn(); results.push(['ok', name, Date.now() - t]); console.log(`  ok   ${name} (${Date.now() - t} ms)`) } catch (e) {
    failed++; results.push(['FAIL', name]); console.log(`  FAIL ${name}\n       ${String(e.stack || e).split('\n').slice(0, 6).join('\n       ')}`)
  }
}

async function axe(page, label) {
  const r = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa', 'best-practice']).analyze()
  const bad = r.violations.filter((v) => ['serious', 'critical', 'moderate'].includes(v.impact))
  assert.equal(bad.length, 0, `axe on ${label}:\n` + bad.map((v) => `${v.id} (${v.impact}): ${v.help} → ${v.nodes.slice(0, 3).map((n) => n.target.join(' ')).join(' | ')}`).join('\n'))
}

